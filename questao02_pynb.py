# Commented out IPython magic to ensure Python compatibility.
import streamlit as st
import random
 
 # ==========================================
 # LÓGICA DA ESTRUTURA DE DADOS
 # ==========================================
class ListaDividida:
     def __init__(self, seed=42, initial_size=1024):
         random.seed(seed)
         # Gera 1024 inteiros distintos ordenados. Intervalo amplo para evitar colisões
         self.sorted_region = sorted(random.sample(range(1, 100000), initial_size))
         self.tail = []
 
     def buscar(self, key):
         # 1. Busca Binária na região ordenada
         left, right = 0, len(self.sorted_region) - 1
         bin_iters = 0
         found_in_sorted = False
 
         while left <= right:
             bin_iters += 1
             mid = (left + right) // 2
             if self.sorted_region[mid] == key:
                 found_in_sorted = True
                 break
             elif self.sorted_region[mid] < key:
                 left = mid + 1
             else:
                 right = mid - 1
 
         if found_in_sorted:
             return {
                 "encontrado": True,
                 "local": "Região Ordenada",
                 "bin_iters": bin_iters,
                 "seq_iters": 0,
                 "total_iters": bin_iters
             }
 
         # 2. Busca Sequencial na cauda
         seq_iters = 0
         found_in_tail = False
         for item in self.tail:
             seq_iters += 1
             if item == key:
                 found_in_tail = True
                 break
 
         if found_in_tail:
             return {
                 "encontrado": True,
                 "local": "Cauda",
                 "bin_iters": bin_iters,
                 "seq_iters": seq_iters,
                 "total_iters": bin_iters + seq_iters
             }
 
         return {
             "encontrado": False,
             "local": "Não encontrado",
             "bin_iters": bin_iters,
             "seq_iters": seq_iters,
             "total_iters": bin_iters + seq_iters
         }
 
     def inserir(self, key):
         busca = self.buscar(key)
         if busca["encontrado"]:
             return False, "Erro: A chave já existe na estrutura."
 
         self.tail.append(key)
         if len(self.tail) == 10:
             self._intercalar()
             return True, "Chave inserida com sucesso. A cauda atingiu 10 elementos e foi ordenada e intercalada à região ordenada!"
 
         return True, f"Chave {key} inserida na cauda com sucesso."
 
def _intercalar(self):
         self.tail.sort()
         new_sorted = []
         i, j = 0, 0
 
         # Intercalação de dois vetores ordenados (Merge)
         while i < len(self.sorted_region) and j < len(self.tail):
             if self.sorted_region[i] < self.tail[j]:
                 new_sorted.append(self.sorted_region[i])
                 i += 1
             else:
                 new_sorted.append(self.tail[j])
                 j += 1
 
         new_sorted.extend(self.sorted_region[i:])
         new_sorted.extend(self.tail[j:])
 
         self.sorted_region = new_sorted
         self.tail = []
 
